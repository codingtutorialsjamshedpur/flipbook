package com.example.service

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import com.example.data.model.DocumentEntity
import com.example.data.model.DocumentFormat
import com.tom_roush.pdfbox.pdmodel.PDDocument
import com.tom_roush.pdfbox.text.PDFTextStripper
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.ByteArrayInputStream

/**
 * Addendum §1 / §11: the demo catalog must build eight real fixtures through the actual
 * parsing pipelines of their formats — never the same canned document under different names.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class DemoCatalogTest {

    private val context: Context = ApplicationProvider.getApplicationContext()

    @Test
    fun `catalog builds all eight samples through their real parsers`() {
        val descriptors = DemoCatalog.descriptors
        assertEquals(8, descriptors.size)

        val samples = descriptors.map { it to DemoCatalog.buildSample(context, it) }
        for ((descriptor, sample) in samples) {
            assertNotNull("sample ${descriptor.id} failed to build", sample)
            val doc = sample as DocumentEntity
            assertEquals(descriptor.id, doc.id)
            assertEquals(descriptor.format, doc.format)
            assertTrue("sample ${descriptor.id} must be tagged isDemo", doc.isDemo)
            assertTrue("sample ${descriptor.id} has blank content", doc.rawContent.isNotBlank())
            assertTrue(doc.totalPages >= 1)
        }
    }

    @Test
    fun `every sample carries distinct real content`() {
        val samples = DemoCatalog.descriptors.mapNotNull { DemoCatalog.buildSample(context, it) }
        assertEquals(8, samples.size)
        assertEquals(8, samples.map { it.rawContent }.distinct().size)
    }

    @Test
    fun `hindi pdf sample is a real pdf with an extractable devanagari text layer`() {
        val doc = DocumentParserService.generateHindiSamplePdf(context)
        assertEquals("demo_pdf_hi_nadi", doc.id)
        assertEquals("नदी और नाव", doc.title)
        assertEquals(DocumentFormat.PDF, doc.format)
        assertTrue(doc.rawContent.contains("नदी"))

        // The generated bytes must be a genuine PDF whose invisible text layer
        // round-trips through PDFTextStripper (search / TTS / vocabulary rely on it).
        val bytes = DocumentParserService.buildHindiSamplePdfBytes(
            context,
            "नदी और नाव",
            "किशोर साहू",
            DemoCatalog.hindiPdfPages
        )
        assertTrue(bytes.size > 1000)
        assertEquals("%PDF", String(bytes, 0, 4, Charsets.US_ASCII))

        val stripped = PDDocument.load(ByteArrayInputStream(bytes)).use { pd ->
            PDFTextStripper().getText(pd)
        }
        assertTrue("text layer lost the title: $stripped", stripped.contains("नदी"))
        assertTrue("text layer lost the footer", stripped.contains("पृष्ठ"))

        for ((pageTitle, _) in DemoCatalog.hindiPdfPages) {
            assertTrue(
                "text layer missing page title '$pageTitle'",
                stripped.contains(pageTitle)
            )
        }
    }

    @Test
    fun `english pdf sample exposes the canonical ten pages`() {
        val doc = DocumentParserService.generate10PageSamplePdf(context)
        assertEquals("The Quantum Manuscript (10 Pages)", doc.title)
        assertEquals(10, doc.totalPages)
        assertTrue(doc.isDemo)
        assertEquals(DocumentFormat.PDF, doc.format)
    }

    @Test
    fun `txt epub and docx samples are parseable real files`() {
        val byId = DemoCatalog.descriptors.associateBy { it.id }

        val txt = DemoCatalog.buildSample(context, byId.getValue("demo_txt_en_lighthouse"))
        assertNotNull(txt)
        assertTrue(txt!!.rawContent.contains("Elsie"))

        val epub = DemoCatalog.buildSample(context, byId.getValue("demo_epub_en_observatory"))
        assertNotNull(epub)
        assertTrue(epub!!.rawContent.isNotBlank())

        val docx = DemoCatalog.buildSample(context, byId.getValue("demo_docx_hi_tyohar"))
        assertNotNull(docx)
        assertTrue(docx!!.rawContent.isNotBlank())

        // Hindi fixtures must actually contain Devanagari text
        val hindiEpub = DemoCatalog.buildSample(context, byId.getValue("demo_epub_hi_jangal"))
        assertTrue(hindiEpub!!.rawContent.any { it.code in 0x0900..0x097F })
    }
}
